    from caixas c join perfis p on p.id = c.usuario_id where c.aberto_em >= ini and c.aberto_em < fim), '[]');
end $$;

create function relatorio_locacoes(p_de date default null, p_ate date default null, p_placa text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente'); ini timestamptz; fim timestamptz;
  v_placa text := nullif(regexp_replace(upper(coalesce(p_placa, '')), '[^A-Z0-9]', '', 'g'), '');
begin
  select * into ini, fim from _intervalo(p_de, p_ate);
  if v_placa is not null then perform _auditar(u.id, 'busca_placa', jsonb_build_object('placa', v_placa)); end if;
  return coalesce((select jsonb_agg(x order by x->>'entrada' desc) from (
    select jsonb_build_object('id', l.id, 'quarto', q.numero, 'placa', l.placa, 'veiculo', l.veiculo, 'tipo', l.tipo,
      'periodo_nome', l.periodo_nome, 'entrada', l.entrada, 'saida', l.saida, 'horas_adicionais', l.horas_adicionais,
      'valor_quarto', l.valor_quarto, 'valor_consumo', l.valor_consumo, 'desconto', l.desconto, 'total', l.total,
      'status', l.status, 'atendente_entrada', pe.nome, 'atendente_saida', ps.nome) x
    from locacoes l join quartos q on q.id = l.quarto_id
    left join perfis pe on pe.id = l.usuario_entrada left join perfis ps on ps.id = l.usuario_saida
    where l.entrada >= ini and l.entrada < fim and (v_placa is null or l.placa = v_placa)
    order by l.entrada desc limit 500) s), '[]');
end $$;

