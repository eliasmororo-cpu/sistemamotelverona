-- Sistema de gestão do motel: tabelas, regras de cobrança e permissões.
-- Toda alteração passa por funções (RPC) que conferem o perfil de quem chama.
-- As tabelas têm RLS ligado e nenhuma política de escrita: o celular não grava direto.

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------- tabelas
create table configuracoes (chave text primary key, valor text not null);

create table perfis (
  id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  login text not null unique,
  papel text not null check (papel in ('admin','gerente','atendente','camareira')),
  ativo boolean not null default true,
  pin_hash text
);

create table categorias (
  id bigint generated by default as identity primary key,
  nome text not null,
  hora_adicional numeric(10,2) not null default 0,
  tolerancia_min int not null default 15,
  pernoite_preco numeric(10,2) not null default 0,
  pernoite_inicio time not null default '20:00',
  pernoite_fim_venda time not null default '05:00',
  pernoite_fim time not null default '12:00',
  ativo boolean not null default true
);

create table periodos (
  id bigint generated by default as identity primary key,
  categoria_id bigint not null references categorias(id),
  nome text not null,
  minutos int not null check (minutos > 0),
  preco numeric(10,2) not null check (preco >= 0),
  ativo boolean not null default true
);

create table quartos (
  id bigint generated by default as identity primary key,
  numero text not null unique,
  categoria_id bigint not null references categorias(id),
  status text not null default 'livre' check (status in ('livre','ocupado','limpeza','manutencao')),
  ativo boolean not null default true
);

create table produtos (
  id bigint generated by default as identity primary key,
  nome text not null,
  preco numeric(10,2) not null check (preco >= 0),
  ativo boolean not null default true
);

create table caixas (
  id bigint generated by default as identity primary key,
  usuario_id uuid not null references perfis(id),
  aberto_em timestamptz not null default now(),
  fechado_em timestamptz,
  valor_inicial numeric(10,2) not null default 0,
  valor_contado numeric(10,2),
  esperado_dinheiro numeric(10,2),
  diferenca numeric(10,2)
);
create unique index caixa_aberto_por_usuario on caixas(usuario_id) where fechado_em is null;

create table movimentos_caixa (
  id bigint generated by default as identity primary key,
  caixa_id bigint not null references caixas(id),
  tipo text not null check (tipo in ('sangria','suprimento')),
  valor numeric(10,2) not null check (valor > 0),
  motivo text not null,
  usuario_id uuid not null references perfis(id),
  criado_em timestamptz not null default now()
);

create table locacoes (
  id bigint generated by default as identity primary key,
  quarto_id bigint not null references quartos(id),
  placa text,
  sem_veiculo boolean not null default false,
  veiculo text,
  tipo text not null check (tipo in ('periodo','pernoite')),
  periodo_id bigint references periodos(id),
  periodo_nome text not null,
  preco_base numeric(10,2) not null,
  hora_adicional numeric(10,2) not null,
  tolerancia_min int not null,
  entrada timestamptz not null default now(),
  limite timestamptz not null,
  saida timestamptz,
  horas_adicionais int,
  valor_quarto numeric(10,2),
  valor_consumo numeric(10,2),
  desconto numeric(10,2) not null default 0,
  desconto_motivo text,
  desconto_autorizado_por uuid references perfis(id),
  total numeric(10,2),
  status text not null default 'aberta' check (status in ('aberta','fechada','cancelada')),
  cancel_motivo text,
  cancel_autorizado_por uuid references perfis(id),
  usuario_entrada uuid not null references perfis(id),
  usuario_saida uuid references perfis(id),
  caixa_id bigint references caixas(id)
);
create index locacoes_entrada on locacoes(entrada);
create index locacoes_saida on locacoes(saida);
create index locacoes_placa on locacoes(placa);
create unique index um_quarto_uma_locacao on locacoes(quarto_id) where status = 'aberta';

create table consumos (
  id bigint generated by default as identity primary key,
  locacao_id bigint not null references locacoes(id),
  produto_id bigint references produtos(id),
  nome text not null,
  quantidade int not null check (quantidade between 1 and 50),
  preco_unit numeric(10,2) not null,
  usuario_id uuid not null references perfis(id),
  criado_em timestamptz not null default now()
);

create table pagamentos (
  id bigint generated by default as identity primary key,
  locacao_id bigint not null references locacoes(id),
  caixa_id bigint not null references caixas(id),
  forma text not null check (forma in ('dinheiro','pix','debito','credito')),
  valor numeric(10,2) not null check (valor > 0)
);

create table limpezas (
  id bigint generated by default as identity primary key,
  quarto_id bigint not null references quartos(id),
  locacao_id bigint references locacoes(id),
  inicio timestamptz not null default now(),
  fim timestamptz,
  usuario_id uuid references perfis(id)
);

-- Registro de tudo que foi feito e por quem. Nenhuma função apaga ou altera esta tabela.
create table auditoria (
  id bigint generated by default as identity primary key,
  usuario_id uuid references perfis(id),
  acao text not null,
  detalhe jsonb,
  criado_em timestamptz not null default now()
);

-- ---------------------------------------------------------------- segurança das tabelas
do $$ declare t text; begin
  foreach t in array array['configuracoes','perfis','categorias','periodos','quartos','produtos','caixas',
    'movimentos_caixa','locacoes','consumos','pagamentos','limpezas','auditoria'] loop
    execute format('alter table %I enable row level security', t);
    execute format('revoke all on %I from anon, authenticated', t);
  end loop;
end $$;

-- ---------------------------------------------------------------- regras de cobrança
create function _tz() returns text language sql immutable as $$ select 'America/Sao_Paulo' $$;

-- Próximo horário (hora local) a partir de um momento. Ex.: entrada 22:00, fim 12:00 -> 12:00 do dia seguinte.
create function _proximo_horario(p_de timestamptz, p_hora time) returns timestamptz
language plpgsql immutable as $$
declare local timestamp := p_de at time zone _tz(); cand timestamp;
begin
  cand := date_trunc('day', local) + p_hora;
  if cand <= local then cand := cand + interval '1 day'; end if;
  return cand at time zone _tz();
end $$;

-- Hora adicional: só cobra depois da tolerância; aí conta cada hora iniciada desde o fim do período.
create function _horas_adicionais(p_limite timestamptz, p_saida timestamptz, p_tol int) returns int
language plpgsql immutable as $$
declare exc numeric := extract(epoch from (p_saida - p_limite)) / 60;
begin
  if exc <= p_tol then return 0; end if;
  return ceil(exc / 60)::int;
end $$;

-- Janela de venda do pernoite (pode atravessar a meia-noite, ex.: 20:00 até 05:00).
create function _pernoite_permitido(p_agora timestamptz, p_ini time, p_fim time) returns boolean
language sql immutable as $$
  select case when p_ini <= p_fim
    then (p_agora at time zone _tz())::time between p_ini and p_fim
    else (p_agora at time zone _tz())::time >= p_ini or (p_agora at time zone _tz())::time <= p_fim end
$$;

-- Placa antiga (ABC1234) ou Mercosul (ABC1D23). Retorna normalizada ou null.
create function _normalizar_placa(p text) returns text language sql immutable as $$
  select case when x ~ '^[A-Z]{3}[0-9][A-Z0-9][0-9]{2}$' then x end
  from (select regexp_replace(upper(coalesce(p, '')), '[^A-Z0-9]', '', 'g') as x) s
$$;

-- ---------------------------------------------------------------- utilidades de acesso
create function _eu() returns perfis language plpgsql stable security definer set search_path = public as $$
declare u perfis;
begin
  select * into u from perfis where id = auth.uid() and ativo;
  if not found then raise exception 'Faça login novamente'; end if;
  return u;
end $$;

create function _exigir(variadic papeis text[]) returns perfis
language plpgsql stable security definer set search_path = public as $$
declare u perfis := _eu();
begin
  if not (u.papel = any(papeis)) then raise exception 'Sem permissão'; end if;
  return u;
end $$;

create function _gestor(u perfis) returns boolean language sql immutable as $$ select u.papel in ('admin','gerente') $$;

-- Desconto, cancelamento e estorno pedem login + PIN de um gerente.
create function _autorizar_gerente(p_login text, p_pin text) returns perfis
language plpgsql stable security definer set search_path = public, extensions as $$
declare g perfis;
begin
  if coalesce(p_login, '') = '' or coalesce(p_pin, '') = '' then raise exception 'Precisa do login e PIN de um gerente'; end if;
  select * into g from perfis where login = lower(trim(p_login)) and ativo and papel in ('admin','gerente');
  if not found or g.pin_hash is null or extensions.crypt(p_pin, g.pin_hash) <> g.pin_hash then
    raise exception 'Autorização de gerente inválida';
  end if;
  return g;
end $$;

create function _auditar(p_usuario uuid, p_acao text, p_detalhe jsonb default null) returns void
language sql security definer set search_path = public as $$
  insert into auditoria (usuario_id, acao, detalhe) values (p_usuario, p_acao, p_detalhe)
$$;

-- ---------------------------------------------------------------- leitura geral
create function eu_perfil() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare u perfis := _eu();
begin
  return jsonb_build_object('id', u.id, 'nome', u.nome, 'login', u.login, 'papel', u.papel,
    'nome_motel', (select valor from configuracoes where chave = 'nome_motel'));
end $$;

create function tabela() returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform _eu();
  return jsonb_build_object(
    'categorias', coalesce((select jsonb_agg(to_jsonb(c) || jsonb_build_object('periodos', coalesce((
        select jsonb_agg(to_jsonb(p) order by p.minutos) from periodos p where p.categoria_id = c.id and p.ativo), '[]'))
      order by c.id) from categorias c where c.ativo), '[]'),
    'produtos', coalesce((select jsonb_agg(to_jsonb(p) order by p.nome) from produtos p where p.ativo), '[]'));
end $$;

create function _conta(l locacoes, p_saida timestamptz) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  horas int := _horas_adicionais(l.limite, p_saida, l.tolerancia_min);
  v_adic numeric := round(horas * l.hora_adicional, 2);
  v_cons numeric; itens jsonb;
begin
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'quantidade', quantidade, 'preco_unit', preco_unit) order by id), '[]'),
         coalesce(sum(quantidade * preco_unit), 0)
    into itens, v_cons from consumos where locacao_id = l.id;
  return jsonb_build_object(
    'locacao_id', l.id, 'entrada', l.entrada, 'limite', l.limite, 'saida', p_saida,
    'minutos', greatest(0, round(extract(epoch from (p_saida - l.entrada)) / 60)),
    'preco_base', l.preco_base, 'horas_adicionais', horas, 'valor_adicional', v_adic,
    'valor_quarto', l.preco_base + v_adic, 'consumos', itens, 'valor_consumo', v_cons,
    'total', l.preco_base + v_adic + v_cons);
end $$;

create function painel() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare u perfis := _eu();
begin
  return jsonb_build_object(
    'agora', now(),
    'caixa', jsonb_build_object('aberto', exists(select 1 from caixas where usuario_id = u.id and fechado_em is null)),
    'quartos', coalesce((select jsonb_agg(
      jsonb_build_object('id', q.id, 'numero', q.numero, 'status', q.status, 'categoria', c.nome, 'categoria_id', c.id)
      || case when l.id is null then '{}'::jsonb else jsonb_build_object('locacao', jsonb_build_object(
        'id', l.id, 'placa', l.placa, 'sem_veiculo', l.sem_veiculo, 'veiculo', l.veiculo, 'tipo', l.tipo,
        'periodo_nome', l.periodo_nome, 'entrada', l.entrada, 'limite', l.limite, 'vencido', now() > l.limite,
        'total_parcial', (_conta(l, now()))->'total')) end
      order by q.numero)
      from quartos q join categorias c on c.id = q.categoria_id
      left join locacoes l on l.quarto_id = q.id and l.status = 'aberta'
      where q.ativo), '[]'));
end $$;

-- ---------------------------------------------------------------- locações
create function abrir_locacao(p_quarto bigint, p_placa text, p_sem_veiculo boolean, p_veiculo text,
  p_tipo text, p_periodo bigint default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  u perfis := _exigir('admin','gerente','atendente');
  q quartos; c categorias; p periodos; v_placa text; v_base numeric; v_limite timestamptz; l locacoes;
begin
  select * into q from quartos where id = p_quarto and ativo for update;
  if not found then raise exception 'Quarto não encontrado'; end if;
  if q.status <> 'livre' then raise exception 'Quarto % não está livre', q.numero; end if;
  select * into c from categorias where id = q.categoria_id;

  if not coalesce(p_sem_veiculo, false) then
    v_placa := _normalizar_placa(p_placa);
    if v_placa is null then raise exception 'Placa inválida. Use ABC1234 ou ABC1D23.'; end if;
    if exists(select 1 from locacoes where status = 'aberta' and placa = v_placa) then
      raise exception 'Esta placa já está em um quarto ocupado';
    end if;
  end if;

  if p_tipo = 'pernoite' then
    if c.pernoite_preco <= 0 then raise exception 'Este quarto não vende pernoite'; end if;
    if not _pernoite_permitido(now(), c.pernoite_inicio, c.pernoite_fim_venda) then
      raise exception 'Pernoite só pode ser vendido entre % e %', to_char(c.pernoite_inicio, 'HH24:MI'), to_char(c.pernoite_fim_venda, 'HH24:MI');
    end if;
    v_base := c.pernoite_preco; v_limite := _proximo_horario(now(), c.pernoite_fim);
  elsif p_tipo = 'periodo' then
    select * into p from periodos where id = p_periodo and categoria_id = q.categoria_id and ativo;
    if not found then raise exception 'Período inválido para este quarto'; end if;
    v_base := p.preco; v_limite := now() + make_interval(mins => p.minutos);
  else
    raise exception 'Tipo de locação inválido';
  end if;

  insert into locacoes (quarto_id, placa, sem_veiculo, veiculo, tipo, periodo_id, periodo_nome,
    preco_base, hora_adicional, tolerancia_min, limite, usuario_entrada)
  values (q.id, v_placa, coalesce(p_sem_veiculo, false), nullif(left(trim(coalesce(p_veiculo, '')), 60), ''), p_tipo, p.id,
    coalesce(p.nome, 'Pernoite'), v_base, c.hora_adicional, c.tolerancia_min, v_limite, u.id)
  returning * into l;
  update quartos set status = 'ocupado' where id = q.id;
  perform _auditar(u.id, 'locacao_aberta', jsonb_build_object('locacao_id', l.id, 'quarto', q.numero, 'placa', v_placa, 'tipo', p_tipo, 'base', v_base));
  return to_jsonb(l);
end $$;

create function _locacao_aberta(p_id bigint) returns locacoes
language plpgsql security definer set search_path = public as $$
declare l locacoes;
begin
  select * into l from locacoes where id = p_id for update;
  if not found then raise exception 'Locação não encontrada'; end if;
  if l.status <> 'aberta' then raise exception 'Locação já encerrada'; end if;
  return l;
end $$;

create function conta_locacao(p_locacao bigint) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare l locacoes; r jsonb;
begin
  perform _eu();
  select * into l from locacoes where id = p_locacao;
  if not found then raise exception 'Locação não encontrada'; end if;
  if l.status = 'aberta' then r := _conta(l, now());
  else r := _conta(l, l.saida) || jsonb_build_object('desconto', l.desconto, 'total', l.total); end if;
  return r || jsonb_build_object('quarto', (select numero from quartos where id = l.quarto_id),
    'placa', l.placa, 'tipo', l.tipo, 'periodo_nome', l.periodo_nome, 'status', l.status);
end $$;

create function lancar_consumo(p_locacao bigint, p_produto bigint, p_quantidade int) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente','camareira'); l locacoes := _locacao_aberta(p_locacao); p produtos;
begin
  select * into p from produtos where id = p_produto and ativo;
  if not found then raise exception 'Produto inválido'; end if;
  if p_quantidade is null or p_quantidade < 1 or p_quantidade > 50 then raise exception 'Quantidade inválida'; end if;
  insert into consumos (locacao_id, produto_id, nome, quantidade, preco_unit, usuario_id) values (l.id, p.id, p.nome, p_quantidade, p.preco, u.id);
  perform _auditar(u.id, 'consumo_lancado', jsonb_build_object('locacao_id', l.id, 'produto', p.nome, 'qtd', p_quantidade, 'preco', p.preco));
  return _conta(l, now());
end $$;

create function estornar_consumo(p_consumo bigint, p_motivo text, p_gerente text, p_pin text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente'); c consumos; l locacoes; g perfis;
begin
  select * into c from consumos where id = p_consumo;
  if not found then raise exception 'Consumo não encontrado'; end if;
  l := _locacao_aberta(c.locacao_id);
  g := _autorizar_gerente(p_gerente, p_pin);
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Informe o motivo'; end if;
  delete from consumos where id = c.id;
  perform _auditar(u.id, 'consumo_estornado', jsonb_build_object('locacao_id', l.id, 'consumo', to_jsonb(c), 'motivo', p_motivo, 'autorizado_por', g.nome));
  return _conta(l, now());
end $$;

create function fechar_locacao(p_locacao bigint, p_pagamentos jsonb, p_desconto numeric default 0,
  p_desconto_motivo text default null, p_gerente text default null, p_pin text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  u perfis := _exigir('admin','gerente','atendente'); l locacoes := _locacao_aberta(p_locacao);
  cx caixas; g perfis; conta jsonb; v_desc numeric := round(coalesce(p_desconto, 0), 2);
  v_total numeric; v_pago numeric := 0; pg jsonb; agora timestamptz := now();
begin
  select * into cx from caixas where usuario_id = u.id and fechado_em is null;
  if not found then raise exception 'Abra o seu caixa antes de receber'; end if;
  conta := _conta(l, agora);
  if v_desc < 0 or v_desc > (conta->>'total')::numeric then raise exception 'Desconto inválido'; end if;
  if v_desc > 0 then
    if coalesce(trim(p_desconto_motivo), '') = '' then raise exception 'Informe o motivo do desconto'; end if;
    g := _autorizar_gerente(p_gerente, p_pin);
  end if;
  v_total := (conta->>'total')::numeric - v_desc;

  for pg in select * from jsonb_array_elements(coalesce(p_pagamentos, '[]')) loop
    if pg->>'forma' not in ('dinheiro','pix','debito','credito') or coalesce((pg->>'valor')::numeric, 0) <= 0 then
      raise exception 'Pagamento inválido';
    end if;
    v_pago := v_pago + round((pg->>'valor')::numeric, 2);
  end loop;
  if abs(v_pago - v_total) > 0.009 then
    raise exception 'Pagamentos (R$ %) não batem com o total (R$ %)', to_char(v_pago, 'FM999990.00'), to_char(v_total, 'FM999990.00');
  end if;

  insert into pagamentos (locacao_id, caixa_id, forma, valor)
    select l.id, cx.id, x->>'forma', round((x->>'valor')::numeric, 2) from jsonb_array_elements(p_pagamentos) x;
  update locacoes set status = 'fechada', saida = agora, horas_adicionais = (conta->>'horas_adicionais')::int,
    valor_quarto = (conta->>'valor_quarto')::numeric, valor_consumo = (conta->>'valor_consumo')::numeric,
    desconto = v_desc, desconto_motivo = case when v_desc > 0 then trim(p_desconto_motivo) end,
    desconto_autorizado_por = g.id, total = v_total, usuario_saida = u.id, caixa_id = cx.id
  where id = l.id;
  update quartos set status = 'limpeza' where id = l.quarto_id;
  insert into limpezas (quarto_id, locacao_id, inicio) values (l.quarto_id, l.id, agora);
  perform _auditar(u.id, 'locacao_fechada', jsonb_build_object('locacao_id', l.id, 'total', v_total, 'desconto', v_desc,
    'autorizado_por', g.nome, 'pagamentos', p_pagamentos));
  return conta || jsonb_build_object('desconto', v_desc, 'total', v_total);
end $$;

create function cancelar_locacao(p_locacao bigint, p_motivo text, p_gerente text, p_pin text) returns void
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente'); l locacoes := _locacao_aberta(p_locacao); g perfis;
begin
  g := _autorizar_gerente(p_gerente, p_pin);
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Informe o motivo'; end if;
  update locacoes set status = 'cancelada', saida = now(), total = 0, cancel_motivo = trim(p_motivo),
    cancel_autorizado_por = g.id, usuario_saida = u.id where id = l.id;
  update quartos set status = 'limpeza' where id = l.quarto_id;
  insert into limpezas (quarto_id, locacao_id) values (l.quarto_id, l.id);
  perform _auditar(u.id, 'locacao_cancelada', jsonb_build_object('locacao_id', l.id, 'motivo', p_motivo, 'autorizado_por', g.nome));
end $$;

create function mudar_status_quarto(p_quarto bigint, p_status text) returns void
language plpgsql security definer set search_path = public as $$
declare u perfis := _eu(); q quartos;
begin
  select * into q from quartos where id = p_quarto for update;
  if not found then raise exception 'Quarto não encontrado'; end if;
  if not ((q.status = 'limpeza' and p_status = 'livre')
       or (_gestor(u) and q.status = 'livre' and p_status = 'manutencao')
       or (_gestor(u) and q.status = 'manutencao' and p_status = 'livre')) then
    raise exception 'Mudança de status não permitida';
  end if;
  update quartos set status = p_status where id = q.id;
  if q.status = 'limpeza' then update limpezas set fim = now(), usuario_id = u.id where quarto_id = q.id and fim is null; end if;
  perform _auditar(u.id, 'quarto_status', jsonb_build_object('quarto', q.numero, 'de', q.status, 'para', p_status));
end $$;

-- ---------------------------------------------------------------- caixa
create function _resumo_caixa(cx caixas) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare din numeric; sup numeric; san numeric;
begin
  select coalesce(sum(valor), 0) into din from pagamentos where caixa_id = cx.id and forma = 'dinheiro';
  select coalesce(sum(valor) filter (where tipo = 'suprimento'), 0), coalesce(sum(valor) filter (where tipo = 'sangria'), 0)
    into sup, san from movimentos_caixa where caixa_id = cx.id;
  return jsonb_build_object(
    'por_forma', coalesce((select jsonb_agg(jsonb_build_object('forma', forma, 'total', t)) from
      (select forma, sum(valor) t from pagamentos where caixa_id = cx.id group by forma) s), '[]'),
    'movimentos', coalesce((select jsonb_agg(to_jsonb(m) order by m.id) from movimentos_caixa m where caixa_id = cx.id), '[]'),
    'esperado_dinheiro', cx.valor_inicial + din + sup - san,
    'locacoes', (select count(*) from locacoes where caixa_id = cx.id));
end $$;

create function meu_caixa() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente'); cx caixas; r jsonb;
begin
  select * into cx from caixas where usuario_id = u.id and fechado_em is null;
  if not found then return jsonb_build_object('aberto', false); end if;
  r := _resumo_caixa(cx);
  -- Fechamento cego: a atendente não vê quanto deveria ter em dinheiro.
  if not _gestor(u) then
    r := r - 'esperado_dinheiro';
    r := jsonb_set(r, '{por_forma}', coalesce((select jsonb_agg(x) from jsonb_array_elements(r->'por_forma') x where x->>'forma' <> 'dinheiro'), '[]'));
  end if;
  return r || jsonb_build_object('aberto', true, 'id', cx.id, 'aberto_em', cx.aberto_em, 'valor_inicial', cx.valor_inicial);
end $$;

create function abrir_caixa(p_valor_inicial numeric) returns void
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente'); v_id bigint;
begin
  if exists(select 1 from caixas where usuario_id = u.id and fechado_em is null) then raise exception 'Você já tem um caixa aberto'; end if;
  if coalesce(p_valor_inicial, 0) < 0 then raise exception 'Valor inválido'; end if;
  insert into caixas (usuario_id, valor_inicial) values (u.id, round(coalesce(p_valor_inicial, 0), 2)) returning id into v_id;
  perform _auditar(u.id, 'caixa_aberto', jsonb_build_object('caixa_id', v_id, 'valor_inicial', p_valor_inicial));
end $$;

create function movimento_caixa(p_tipo text, p_valor numeric, p_motivo text) returns void
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente'); cx caixas;
begin
  select * into cx from caixas where usuario_id = u.id and fechado_em is null;
  if not found then raise exception 'Nenhum caixa aberto'; end if;
  if p_tipo not in ('sangria','suprimento') or coalesce(p_valor, 0) <= 0 then raise exception 'Movimento inválido'; end if;
  if coalesce(trim(p_motivo), '') = '' then raise exception 'Informe o motivo'; end if;
  insert into movimentos_caixa (caixa_id, tipo, valor, motivo, usuario_id) values (cx.id, p_tipo, round(p_valor, 2), trim(p_motivo), u.id);
  perform _auditar(u.id, 'caixa_movimento', jsonb_build_object('caixa_id', cx.id, 'tipo', p_tipo, 'valor', p_valor, 'motivo', p_motivo));
end $$;

create function fechar_caixa(p_valor_contado numeric) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin','gerente','atendente'); cx caixas; esperado numeric; dif numeric;
begin
  select * into cx from caixas where usuario_id = u.id and fechado_em is null for update;
  if not found then raise exception 'Nenhum caixa aberto'; end if;
  if p_valor_contado is null or p_valor_contado < 0 then raise exception 'Informe quanto há em dinheiro na gaveta'; end if;
  esperado := (_resumo_caixa(cx)->>'esperado_dinheiro')::numeric;
  dif := round(p_valor_contado, 2) - esperado;
  update caixas set fechado_em = now(), valor_contado = round(p_valor_contado, 2), esperado_dinheiro = esperado, diferenca = dif where id = cx.id;
  perform _auditar(u.id, 'caixa_fechado', jsonb_build_object('caixa_id', cx.id, 'contado', p_valor_contado, 'esperado', esperado, 'diferenca', dif));
  if _gestor(u) then return jsonb_build_object('ok', true, 'esperado', esperado, 'diferenca', dif); end if;
  return jsonb_build_object('ok', true);
end $$;

-- ---------------------------------------------------------------- relatórios (dono / gerente)
create function _intervalo(p_de date, p_ate date, out ini timestamptz, out fim timestamptz)
language sql stable as $$
  select (coalesce(p_de, (now() at time zone _tz())::date))::timestamp at time zone _tz(),
         (coalesce(p_ate, p_de, (now() at time zone _tz())::date) + 1)::timestamp at time zone _tz()
$$;

create function _fechadas(ini timestamptz, fim timestamptz)
returns table (id bigint, quarto text, atendente text, entrada timestamptz, saida timestamptz, minutos numeric,
  total numeric, valor_quarto numeric, valor_consumo numeric, desconto numeric, desconto_motivo text)
language sql stable security definer set search_path = public as $$
  select l.id, q.numero, coalesce(p.nome, '-'), l.entrada, l.saida, extract(epoch from (l.saida - l.entrada)) / 60,
         l.total, l.valor_quarto, l.valor_consumo, l.desconto, l.desconto_motivo
  from locacoes l join quartos q on q.id = l.quarto_id left join perfis p on p.id = l.usuario_saida
  where l.status = 'fechada' and l.saida >= ini and l.saida < fim
$$;

create function relatorio_resumo(p_de date default null, p_ate date default null) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare ini timestamptz; fim timestamptz; nq int; min_periodo numeric; r jsonb;
begin
  perform _exigir('admin','gerente');
  select * into ini, fim from _intervalo(p_de, p_ate);
  select count(*) into nq from quartos where ativo;
  min_periodo := greatest(1, extract(epoch from (least(fim, now()) - ini)) / 60);

  select jsonb_build_object(
    'locacoes', count(*), 'faturamento', coalesce(sum(total), 0), 'quartos', coalesce(sum(valor_quarto), 0),
    'consumo', coalesce(sum(valor_consumo), 0), 'descontos', coalesce(sum(desconto), 0),
    'ticket_medio', coalesce(round(avg(total), 2), 0), 'permanencia_media_min', coalesce(round(avg(minutos)), 0),
    'ocupacao_pct', least(100, round(coalesce(sum(minutos), 0) / (greatest(nq, 1) * min_periodo) * 100, 1)))
  into r from _fechadas(ini, fim) f;

  r := r || jsonb_build_object(
    'de', (ini at time zone _tz())::date, 'ate', ((fim at time zone _tz())::date - 1),
    'por_dia', coalesce((select jsonb_agg(jsonb_build_object('chave', d, 'total', t, 'locacoes', n) order by d) from
      (select (saida at time zone _tz())::date::text d, sum(total) t, count(*) n from _fechadas(ini, fim) f group by 1) s), '[]'),
    'por_hora_entrada', coalesce((select jsonb_agg(jsonb_build_object('chave', h, 'total', t, 'locacoes', n) order by h) from
      (select extract(hour from entrada at time zone _tz())::int h, sum(total) t, count(*) n from _fechadas(ini, fim) f group by 1) s), '[]'),
    'por_quarto', coalesce((select jsonb_agg(jsonb_build_object('chave', quarto, 'total', t, 'locacoes', n) order by t desc) from
      (select quarto, sum(total) t, count(*) n from _fechadas(ini, fim) f group by 1) s), '[]'),
    'por_atendente', coalesce((select jsonb_agg(jsonb_build_object('chave', atendente, 'total', t, 'locacoes', n) order by t desc) from
      (select atendente, sum(total) t, count(*) n from _fechadas(ini, fim) f group by 1) s), '[]'),
    'por_forma', coalesce((select jsonb_agg(jsonb_build_object('chave', forma, 'total', t, 'locacoes', n)) from
      (select pg.forma, sum(pg.valor) t, count(*) n from pagamentos pg join _fechadas(ini, fim) f on f.id = pg.locacao_id group by 1) s), '[]'),
    'com_desconto', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'quarto', quarto, 'desconto', desconto,
      'motivo', desconto_motivo, 'atendente', atendente, 'saida', saida)) from _fechadas(ini, fim) f where desconto > 0), '[]'),
    'canceladas', coalesce((select jsonb_agg(jsonb_build_object('id', l.id, 'quarto', q.numero, 'motivo', l.cancel_motivo,
      'entrada', l.entrada, 'saida', l.saida, 'atendente', p.nome))
      from locacoes l join quartos q on q.id = l.quarto_id left join perfis p on p.id = l.usuario_saida
      where l.status = 'cancelada' and l.saida >= ini and l.saida < fim), '[]'),
    'em_aberto', (select count(*) from locacoes where status = 'aberta'));
  return r;
end $$;

create function relatorio_caixas(p_de date default null, p_ate date default null) returns jsonb
