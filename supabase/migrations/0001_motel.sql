-- ---------------------------------------------------------------- configuração (somente admin)
create function _colunas_admin(p_entidade text) returns jsonb language sql immutable as $$
  select case p_entidade
    when 'categorias' then '{"nome":"text","hora_adicional":"numeric","tolerancia_min":"int","pernoite_preco":"numeric",
      "pernoite_inicio":"time","pernoite_fim_venda":"time","pernoite_fim":"time","ativo":"boolean"}'::jsonb
    when 'periodos' then '{"categoria_id":"bigint","nome":"text","minutos":"int","preco":"numeric","ativo":"boolean"}'::jsonb
    when 'quartos' then '{"numero":"text","categoria_id":"bigint","ativo":"boolean"}'::jsonb
    when 'produtos' then '{"nome":"text","preco":"numeric","ativo":"boolean"}'::jsonb
  end
$$;

create function admin_listar(p_entidade text) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare r jsonb;
begin
  perform _exigir('admin');
  if p_entidade = 'usuarios' then
    return coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'login', login, 'papel', papel,
      'ativo', ativo, 'tem_pin', pin_hash is not null) order by nome) from perfis), '[]');
  end if;
  if _colunas_admin(p_entidade) is null then raise exception 'Entidade inválida'; end if;
  execute format('select coalesce(jsonb_agg(to_jsonb(t) order by t.id), ''[]'') from %I t', p_entidade) into r;
  return r;
end $$;

create function admin_salvar(p_entidade text, p_id bigint, p_dados jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare u perfis := _exigir('admin'); cols jsonb := _colunas_admin(p_entidade); k text; sets text[] := '{}'; nomes text[] := '{}'; vals text[] := '{}'; v_id bigint;
begin
  if cols is null then raise exception 'Entidade inválida'; end if;
  for k in select jsonb_object_keys(p_dados) loop
    if cols ? k then
      sets := sets || format('%I = ($1->>%L)::%s', k, k, cols->>k);
      nomes := nomes || format('%I', k);
      vals := vals || format('($1->>%L)::%s', k, cols->>k);
    end if;
  end loop;
  if cardinality(sets) = 0 then raise exception 'Nada para salvar'; end if;
  if p_id is null then
    execute format('insert into %I (%s) values (%s) returning id', p_entidade, array_to_string(nomes, ', '), array_to_string(vals, ', '))
      into v_id using p_dados;
  else
    execute format('update %I set %s where id = $2 returning id', p_entidade, array_to_string(sets, ', '))
      into v_id using p_dados, p_id;
    if v_id is null then raise exception 'Registro não encontrado'; end if;
  end if;
  perform _auditar(u.id, 'config_' || p_entidade, jsonb_build_object('id', v_id) || p_dados);
  return v_id;
end $$;

-- Usado pela função admin-usuarios (que cria o login no Supabase Auth) e pelo admin no painel.
create function admin_salvar_perfil(p_id uuid, p_nome text, p_login text, p_papel text, p_ativo boolean, p_pin text default null) returns void
language plpgsql security definer set search_path = public, extensions as $$
declare quem uuid;
begin
  -- Pelo celular (role authenticated) só o admin. Pelo editor SQL do Supabase ou pela função admin-usuarios, liberado.
  if current_setting('role') in ('authenticated', 'anon') and coalesce(auth.role(), '') <> 'service_role' then
    quem := (_exigir('admin')).id;
  end if;
  if quem is not null and quem = p_id and (not coalesce(p_ativo, true) or p_papel <> 'admin') then
    raise exception 'Você não pode desativar ou rebaixar o próprio usuário';
  end if;
  if coalesce(trim(p_nome), '') = '' then raise exception 'Informe o nome'; end if;
  if lower(trim(coalesce(p_login, ''))) !~ '^[a-z0-9._-]{3,30}$' then
    raise exception 'Login deve ter de 3 a 30 letras ou números, sem espaço nem acento';
  end if;
  if p_pin is not null and p_pin !~ '^[0-9]{4,8}$' then raise exception 'O PIN precisa ter de 4 a 8 números'; end if;
  insert into perfis (id, nome, login, papel, ativo, pin_hash)
  values (p_id, p_nome, lower(trim(p_login)), p_papel, coalesce(p_ativo, true),
          case when p_pin is not null then extensions.crypt(p_pin, extensions.gen_salt('bf')) end)
  on conflict (id) do update set nome = excluded.nome, login = excluded.login, papel = excluded.papel, ativo = excluded.ativo,
    pin_hash = coalesce(excluded.pin_hash, perfis.pin_hash);
  perform _auditar(quem, 'config_usuarios', jsonb_build_object('id', p_id, 'nome', p_nome, 'login', p_login, 'papel', p_papel,
    'ativo', p_ativo, 'pin_alterado', p_pin is not null));
end $$;

