-- LGPD: depois do prazo a placa vira ABC****. Os valores continuam para a contabilidade.
create function mascarar_placas_antigas() returns int language plpgsql security definer set search_path = public as $$
declare dias int := coalesce((select valor::int from configuracoes where chave = 'dias_guardar_placa'), 90); n int;
begin
  update locacoes set placa = left(placa, 3) || '****', veiculo = null
  where status <> 'aberta' and entrada < now() - make_interval(days => dias) and placa is not null and placa not like '%*%';
  get diagnostics n = row_count;
  return n;
end $$;

